"""k4_check.py —— 用【统一口径】重算收益/回撤，并检验 K-4 的触发性质"""
rows = [
    ('P2 2017.01-2022.05', 'bh', 76.69, 55.17, 5.41),
    ('P1 2022.06-2025.05', 'bh', 104.41, 36.37, 3.0),
    ('P3 2019.06-2022.05', 'bh', 148.96, 31.45, 3.0),
    ('P4 2021.06-2024.05', 'bh', 305.30, 24.17, 3.0),
    ('P4 2021.06-2024.05', 'grid200', 323.56, 32.63, 3.0),
    ('P3 2019.06-2022.05', 'grid200', 144.54, 32.79, 3.0),
    ('P1 2022.06-2025.05', 'grid200', 77.64, 43.36, 3.0),
]
out = []
for n, k, net, dd, yr in rows:
    ann = net / 300.0 / yr * 100
    out.append((ann / dd, n, k, net, dd, yr, ann))
print('=' * 88)
print('统一口径 = 年化% / DD%     （报告_003 用的就是这个口径）')
print('=' * 88)
print('%-22s %-8s %9s %8s %6s %9s %11s' % ('window', 'cfg', 'net', 'DD%', 'yrs', 'ann%', 'ann/DD'))
for r, n, k, net, dd, yr, ann in sorted(out, reverse=True):
    print('%-22s %-8s %9.2f %8.2f %6.2f %9.2f %11.3f' % (n, k, net, dd, yr, ann, r))
print()
print('★ P2 归一化后 = %.3f   （家长写的是 0.15；P2 是 5.41 年，不是 3 年）'
      % ((76.69 / 300 / 5.41 * 100) / 55.17))
print('★ 分布跨度 = %.3f ~ %.3f = %.1f 倍，全部来自【选哪个窗口】'
      % (min(r[0] for r in out), max(r[0] for r in out),
         max(r[0] for r in out) / min(r[0] for r in out)))
print()
print('=' * 88)
print('P1 的止盈曲线（grid3 tpmid + tphi，全在 P1 上）')
print('=' * 88)
sw = [(200, 77.64, 43.36), (400, 86.94, 42.69), (600, 85.91, 43.06), (800, 94.67, 42.44),
      (1000, 95.97, 42.21), (1200, 96.84, 41.87), (1400, 101.17, 41.47), (1600, 91.20, 42.35),
      (1800, 96.27, 41.92), (2000, 97.04, 41.82), (2200, 98.93, 41.71), (2400, 96.22, 42.05),
      (3000, 102.35, 41.20), (6000, 99.07, 40.64), (9000, 102.23, 40.58), (12000, 100.46, 39.24),
      (15000, 92.93, 40.17), (18000, 101.73, 41.10), (21000, 98.47, 42.13), (24000, 93.52, 36.37),
      (27000, 89.73, 36.37), (30000, 82.47, 36.37), (100000, 104.41, 36.37)]
print('%9s %9s %8s %10s' % ('TP', 'net', 'DD%', 'ann/DD'))
for tp, net, dd in sw:
    print('%9d %9.2f %8.2f %10.3f' % (tp, net, dd, (net / 300 / 3 * 100) / dd))
print()
nets = [n for _, n, _ in sw[:-1]]
print('★ 12+10=22 个止盈档里，net 最大 = %.2f（TP=%d）；买入持有(TP=inf) = %.2f'
      % (max(nets), sw[nets.index(max(nets))][0], 104.41))
print('★ DD 只从 43.36%% 走到 36.37%%（跨度 7 个百分点），而 net 从 77.64 走到 104.41')
print('  → 22 个止盈档的 DD 几乎不动 ⇒ DD 由【持有单一多头头寸的浮动】决定，不由止盈规则决定')
